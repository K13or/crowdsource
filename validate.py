#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Линтер батчей перевода: ловит поломки ДО вливания в игру.

Запуск:
    python validate.py                 # проверить все батчи crowdsource/*/*.csv
    python validate.py new/new_001.csv # конкретный файл/папку
    python validate.py --warnings      # показать и предупреждения (по умолчанию только ошибки)

Проверяет только НЕпустые переводы. Коды выхода: 0 — ошибок нет, 1 — есть ошибки.

ОШИБКИ (блокируют релиз):
  - набор плейсхолдеров/тегов (%str1%, <c=…>, [lbracket]/[rbracket]/[null]) не совпадает с оригиналом;
  - число %% не совпадает (одиночный % движок примет за начало спецификатора);
  - в переводе остался маркер оригинала [s], [pl:"…"], [f:"…"], [pf:]/[pm:]
    (не преобразован в группу форм: [форма1|форма2|форма3] для числа, [м|ж] для рода);
  - несбалансированные скобки [ ] или теги <c>…</c>;
  - символ U+FFFD (битая кодировка);
  - потерян структурный префикс «Recipe[s]: », «Chest[s]: » и т.п. (в переводе нет двоеточия);
  - две формы в плюрал-группе, когда в оригинале [s]/[pl:…] — русскому нужно три (1 / 2-4 / 5+);
  - четыре формы и больше: движок берёт из группы ровно три, лишняя уедет мусором;
  - пробел вместо формы («Пол[ |а|ов]») или пустая форма в середине группы
    («зон[ы||]» напечатает «1 зоны») — окончание потеряно; пустые по краям
    законны: «Ящик[|а|ов]», «секунд[а|ы|]», «раз[|а|]»;
  - скобочная группа вообще без | при [s]/[pl:…] в оригинале («Ящик[и]» вместо
    «[Ящик|Ящика|Ящиков]») — в игре отрендерится литералом вместе со скобками;
  - потерян родовой маркер [M]/[F] в начале строки;
  - запрещённая GLOSSARY.md форма имени, когда оригинал именно про этот термин
    («Crystal Oasis» -> ~~Хрустальный Оазис~~); «хрустальная банка» не трогается;
  - «висячий» знак ударения (U+0301) не на гласной — след опечатки;
  - латинская буква-двойник внутри русского слова («Лом Пактa»);
  - потерян перенос строки: игра рисует строку так, как её разбил оригинал,
    и без переноса фразы склеиваются («…площадке.Примечание:»);
  - потеряна подпись письма («—Rytlock» после пустой строки);
  - краевые пробелы не совпали с оригиналом — ломается склейка «Рецепт: » + название;
  - невидимый символ, которого нет в оригинале (zero-width, мягкий перенос):
    принесён копипастой, ломает поиск по строке и подстановку имён.

ПРЕДУПРЕЖДЕНИЯ (не блокируют):
  - лишний перенос строки в переводе (чаще хвостовой);
  - потерян неразрывный пробел или маркер списка • — страдает вид, не смысл;
  - скобочная группа без | там, где в оригинале нет [s]/[pl:…];
  - группа форм, а в оригинале ни [s]/[pl:…], ни числа рядом («[Сундук|Сундука|
    Сундуков] Амнитаса») — выбирать форму движку не по чему;
  - все формы в группе одинаковые («[Мини|Мини]»);
  - пустая форма 5+ при основе на стечение согласных: «секунд[а|ы|]» законно
    («5 секунд»), а «краск[а|и|]» даст «5 краск» вместо «красок» — беглая гласная;
  - плюрал-разметка потеряна совсем: в оригинале [s]/[pl:…] и рядом %num%, а в
    переводе скобок нет («Осмотрите %num1%/%num2% виды») — одна форма на все числа;
  - английский Title Case, перенесённый в русский («Знамя Поиска Магии»), — только
    одиночная заглавная в прозе: слово из слоя имён pn_*/GLOSSARY и слово рядом
    с другим заглавным («Дух Медведя») считаются частью названия и не метятся;
  - zero-width символы;
  - перевод дословно равен английскому предложению (возможно, не переведено);
  - у оригинала потеряна разметка: на сервере строка несёт %num2%/[s], а наша
    копия пришла без них («Complete  event.» вместо «Complete %num2% event[s].»).
    Сверка с sync/server_strings.csv; без этого файла проверка выключена;
  - похоже, потеряно число: точной реконструкции нет, но рядом стоит серверная
    строка с числом, а у нашей на его месте остался след — заглушка «x%»
    («Ascalonians remaining: x%» вместо «%num1%%%»), оборванное двоеточие
    («Waves defeated:»), голая косая. Ищется по расстоянию Левенштейна;
  - «ты» и «вы» в одной строке (разнобой обращения);
  - оригинал кончается на .!? — перевод нет (потерянная точка);
  - пробел перед знаком препинания.

ПРЕДУПРЕЖДЕНИЯ по русской типографике (свод правил, README → «Русская типографика»):
  - потеряна буква ё в слове, где написания через «е» не существует («еще», «придет»);
  - сочетание знаков, которого в русском нет: «!?», «...?», «???», «??!»;
    допустимы только ?! ?!! !! !!! ?.. !.. ?!. ...;
  - точка внутри кавычек («…клинка.» вместо «…клинка».);
  - рисунок кавычек: прямые вместо «ёлочек», разнобой в одной строке,
    непарные кавычки, вложенные кавычки того же рисунка (внутренние — „…“);
  - звукоподражание без дефиса («Ааа!» вместо «А-а-а!»);
  - «Вы» с прописной (это из деловой переписки, а не из игрового текста);
  - падежное окончание при цифре («5-ый» вместо «5-й», «5-ого» вместо «5-го»);
  - слова вне стандарта интерфейса: «кликнуть», «юнит», «хиты», «левый щелчок»,
    «опции» при Options, «назначение клавиш» при Controls;
  - переведённое название языка в меню выбора языка;
  - «Бог» с прописной в устойчивом обороте («не дай Бог», «Боже мой»).
"""
