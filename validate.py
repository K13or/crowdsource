_LETTERS = re.compile(r'[^a-z]')
# След изъятия. Без него эвристика метит и законные подписи интерфейса: рядом с
# «Motes Collected» в игре просто существует счётчик «%num1%/%num2% Motes
# Collected», и это две разные строки, а не порча. Ловим только то, где на месте
# числа что-то осталось: зазор, голая косая, оборванное двоеточие, заглушка «x».
SEAM = re.compile(r'[A-Za-z0-9]  +[A-Za-z0-9]|\s/\s|[:—-]\s*$|:\s*[xX]\b|\bx\s*%|'
                  r'\(\s*\)|\[\s*\]|^\s|\s$')
_near_cache = {}

def _bare(s):
    return re.sub(r'\s+', ' ', SERVER_NUM.sub('', s)).strip()

def server_near(en):
    """Похожая серверная строка, у которой число есть, а у нашей копии нет.

    Решает не расстояние само по себе, а ЧТО разошлось. У настоящей потери
    различие только в разметке и пунктуации; если разошлись буквы — это просто
    соседняя строка: «Unlock all  Fused weapon skins» подтягивался к «Unlock all
    %num2% Auric weapon skins», хотя наборы обликов разные. Поэтому решающая
    проверка — расстояние по одним буквам, без цифр и знаков.
    """
    if en in _near_cache:
        return _near_cache[en]
    if not SEAM.search(en):
        _near_cache[en] = None
        return None
    res = None
    k = server_skel(en)
    cand = set(SRV_PRE.get(k[:10], ())) | set(SRV_SUF.get(k[-10:], ()))
    if cand:
        flat = re.sub(r'\s+', ' ', en).strip()
        best, bd = None, 99
        for c in cand:
            d = edit_distance(flat, _bare(c), cap=8)
            if d < bd:
                best, bd = c, d
        if best is not None and 0 < bd <= 6:
            ld = edit_distance(_LETTERS.sub('', flat.lower()),
                               _LETTERS.sub('', _bare(best).lower()), cap=4)
            if ld <= 2:
                res = f"похоже, потеряно число, на сервере: «{best[:60]}»"
    _near_cache[en] = res
    return res

def server_check(en):
    """Предупреждение, если у строки на сервере есть разметка, а у нашей копии нет."""
    if not SERVER_STRINGS or SRV_MARKUP.search(en):
        return None
    cand = SERVER_STRINGS.get(server_skel(en))
    if not cand:
        return None
    # Совпадение по скелету значит «та же строка без разметки». Берём ближайший
    # по Левенштейну вариант: скелет мог свести несколько родственных строк.
    best = min(cand, key=lambda c: edit_distance(en, c))
    if edit_distance(en, best) == 0:
        return None
    # Считаем только числовые плейсхолдеры. Обёртка %str1%%str2%…%str3%%str4% —
    # это отдельная строка игры (шаблон подстановки имени), а не наша испорченная
    # копия: «Corrupted Hero Greatsword» и «%str1%%str2%Corrupted Hero Greatsword%str3%%str4%»
    # существуют обе. По скелету они неразличимы, и на них проверка давала 6 246
    # ложных срабатываний из 6 311.
    lost = sorted(set(re.findall(r'%num\d*%', best)) - set(re.findall(r'%num\d*%', en)))
    if not lost:
        return None
    # Плейсхолдер, приклеенный к слову вплотную («M%num1%», «brood%num1%»), при
    # удалении не оставляет следа, и наша строка — не обрезок, а отдельное имя.
    # След оставляет только отдельно стоящий токен.
    if not any(re.search(r'(?:^|[^A-Za-z0-9])' + re.escape(p) + r'(?:[^A-Za-z0-9]|$)', best)
               for p in lost):
        return None
    # Решающая проверка: снимаем с серверной строки разметку и требуем СОВПАДЕНИЯ
    # с нашей буква в букву. Скелет игнорирует пробелы, поэтому сам по себе он
    # сводит и неродственные строки; точная реконструкция — не сводит.
    if re.sub(r'\s+', ' ', re.sub(r'%num\d*%|\[s\]|\[pl:"[^"]*"\]', '', best)).strip() \
            != re.sub(r'\s+', ' ', en).strip():
        return None
    return f"потеряна разметка оригинала ({' '.join(lost)}), на сервере: «{best[:60]}»"

# Число — единственная часть строки, которую перевод обязан повторить дословно, и
# единственный смысловой сдвиг, который вообще ловится машиной: «Contains 200» ->
# «Содержит 300» игрок видит как враньё. Разделитель тысяч нормализуем (1,400 =
# 1400), внутрь плейсхолдеров (%num1%) не лезем — там цифра часть имени.
# Цифра, приклеенная к букве, — часть имени, а не величина: FRU1TPUNCH, IIX0.
_NB = r'(?<![A-Za-z0-9])'
NUMBER = re.compile(_NB + r'\d{1,3}(?:[, ]\d{3})+(?![A-Za-z0-9])|'
                    + _NB + r'\d+(?![A-Za-z0-9])')

def numbers(s):
    """Числа строки. Плейсхолдеры и теги выкидываем: цифра в %num1% и <c=@a1> —
    часть имени токена, а не величина."""
    s = re.sub(r'%\w+%|<[^>]+>|\[pl:"[^"]*"\]', ' ', s)
    # «0330 hours» по-русски пишут «03:30» — это то же число, а не потеря.
    s = re.sub(r'(?<=\d):(?=\d)', '', s)
    # «120 x 240» и «120x240» — одно и то же, знак умножения не часть числа.
    s = re.sub(r'(?<=\d)\s*[xх×]\s*(?=\d)', ';', s)
    return {re.sub(r'[, ]', '', m.group()) for m in NUMBER.finditer(s)}

