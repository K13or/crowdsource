TOK = re.compile(r'%\w+%|<[^>]+>|\[lbracket\]|\[rbracket\]|\[null\]')
CYR = re.compile(r'[а-яёА-ЯЁ]')
# Маркеры оригинала, которые обязаны раствориться в группе форм. [f:] — род,
# [pf:]/[pm:] — род с числом (французский клиент). В переводе любой из них
# отрендерится литералом вместе со скобками, как и забытый [pl:].
LEFTOVER = re.compile(r'\[s\]|\[pl:|\[f:|\[p[fm]:')
ZW = re.compile(r'[​‌‍﻿]')
ZW_CHARS = "​‌‍⁠﻿­"
# Пробельные символы, которые держат склейку. Перенос строки сюда НЕ входит:
# он про вёрстку и проверяется отдельно.
EDGE_WS = " \t             　"
NOSPACE = re.compile(r'\s+')
# Подпись письма: последняя строка вида «—Rytlock», «— Warmaster Jofast».
SIGNATURE = re.compile(r'\n[ \t]*[—–][ \t]*([^\n]{2,40})[ \t]*$')
# ["s"] — тот же плюрал-маркер, только кавычки уехали внутрь скобки (ArenaNet,
# «Recollection["s"] of the Bearkin's Hunts»). Без этого варианта правило считает,
# что склонять не по чему, и ругается на верную группу форм.
# Родовой маркер оригинала. Если он есть, двухформенная группа в переводе —
# это род («Бог[|иня]»), а не потерянная третья форма числа, даже когда рядом [s].
GENDER_SRC = re.compile(r'\[f:|\[p[fm]:')
PLURAL_EN = re.compile(r'\[s\]|\[pl:|\["s"\]')
NUM_PH = re.compile(r'%num\d*%')
# «Recipe[s]: », «Trophy: » — структурный префикс имени предмета. Если в переводе
# нет двоеточия, слово-префикс просто потеряли (так new_023 лишился всех «Рецепт»).
PREFIX_EN = re.compile(r'^[A-Z][A-Za-z\' -]{2,30}(?:\[s\]|\[pl:"[^"]*"\]):\s')
# Знак ударения ставится на гласную; на согласной/кавычке — мусор от набора.
STRESS_OK = re.compile(r'[аеёиоуыэюяАЕЁИОУЫЭЮЯ]́')
STRESS_ANY = re.compile(r'[̀-ͯ]')
TY = re.compile(r'\b(ты|тебя|тебе|тобой|твой|твоя|твоё|твои|твоего|твоей|твоих|твою|твоим|твоём)\b', re.I)
# Латинская буква-двойник внутри русского слова («Лом Пактa» — последняя 'a' латинская).
# Глазом не видно, а слово уже не русское: ломается поиск и подстановка имён.
# Ошибкой считаем только два случая — буква зажата кириллицей («кастoранской») или
# строчная буква в конце русского слова («Пактa»). Заглавная латиница после кириллицы
# обычно склеенное сокращение («ДеббиP.S.»), а латиница рядом с латиницей — имя («Kye»).
HOMO = set('aceopxyABCEHKMOPTX')

def homoglyph(s):
    def cyr(ch):
        return bool(ch) and ('а' <= ch.lower() <= 'я' or ch.lower() == 'ё')
    for i, ch in enumerate(s):
        if ch not in HOMO or not cyr(s[i-1] if i else ''):
            continue
        nxt = s[i+1] if i + 1 < len(s) else ''
        if cyr(nxt) or (ch.islower() and not (nxt.isascii() and nxt.isalpha())):
            return s[max(0, i-8):i+8]
    return None
VY = re.compile(r'\b(вы|вас|вам|вами|ваш|ваша|ваше|ваши|вашего|вашей|ваших|вашу|вашим|вашем)\b', re.I)

def tokens(s):
    return sorted(TOK.findall(s))

# Служебные токены движка в квадратных скобках — это НЕ плюрал-группы [a|b|c],
# поэтому перед проверкой скобок их убираем (иначе ложное «скобка без |»).
# [M]/[F] — родовой маркер в начале строки, корпус его всегда сохраняет.
KNOWN_TOKENS = re.compile(r'\[(?:lbracket|rbracket|null|plur|nosep|topic-[fm]|f|an|the|[MF])\]|\[pl:"[^"]*"\]')
GENDER_MARK = re.compile(r'^\[([MF])\]')
# Основа перед группой форм — нужна, чтобы судить о пустой форме 5+.
GROUP_STEM = re.compile(r'([А-Яа-яЁё-]*)(\[[^\]]*\])')
# Пустая форма 5+ законна, когда голая основа и есть родительный множественного:
# «секунд[а|ы|]» -> «5 секунд», «руин[у|ы|]» -> «5 руин». Но если основа кончается
# стечением согласных, родительному нужна беглая гласная, и пустая форма врёт:
# «краск[а|и|]» -> «5 краск» вместо «красок», «башн[ю|и|]» -> «башн» вместо «башен».
FLEETING = re.compile(r'(?:[бвгджзйклмнпрстфхцчшщь]к|[бвгджзклмпрстфхшщр]н|[льнй]ц|сл)$')

def empty_forms(stem, grp, forms, warns):
    """Пустые формы внутри группы: где законны, где брак."""
    errs = []
    # Пробел — не форма: «Пол[ |а|ов]» напечатает «Пол » с висячим пробелом.
    if any(f and not f.strip() for f in forms):
        errs.append(f"пробел вместо формы в группе: {grp}")
        return errs
    empty = [i for i, f in enumerate(forms) if not f]
    # Край группы пустым быть вправе: первая форма — режим окончаний («Ящик[|а|ов]»),
    # последняя — основа и есть родительный множественного. Пустыми могут быть и обе
    # сразу: «раз[|а|]» -> «1 раз / 2 раза / 5 раз». А вот пустая в середине — это
    # потерянное окончание («зон[ы||]» напечатает «1 зоны»).
    if empty and len(empty) < len(forms):
        mid = [i for i in empty if i not in (0, len(forms) - 1)]
        if mid:
            errs.append(f"пустая форма в середине группы: {grp}")
    if (not errs and empty and empty[-1] == len(forms) - 1
            and len(forms) == 3 and FLEETING.search(stem.lower())):
        warns.append(f"пустая форма 5+ при основе на стечение согласных — "
                     f"нужна беглая гласная: {stem}{grp} -> «{stem}»")
    return errs

# Слово перед группой, которое в группе же и повторено (см. проверку ниже).
DUP_WORD = re.compile(r'([А-Яа-яЁё-]{4,})\[([^\]\[]*\|[^\]\[]*)\]')

def strip_known(s):
    s = re.sub(r'%\w+%', '', s)
    s = re.sub(r'<[^>]+>', '', s)
    return KNOWN_TOKENS.sub('', s)

# Запрещённые формы имён берём прямо из GLOSSARY.md — из колонки «НЕ так» (~~форма~~).
# Правило привязано к оригиналу: ругаемся на «Хрустальный оазис» только когда в EN
# действительно Crystal Oasis, иначе поймали бы честную хрустальную банку.
# Запрещённая форма записана в глоссарии в именительном падеже, а в тексте она
# стоит в любом. Сравнение по точной строке пропускало «Криты», «ледорождённых»,
# «Древних драконов» — то есть почти всё, кроме словарной формы. Собираем из слова
# основу и допускаем за ней русское окончание; основа короче четырёх букв не
# склоняется, чтобы не ловить однокоренной мусор.
RU_END = ('ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ому|ему|ым|им|ом|ем|ых|их|ыми|ими|ую|юю'
          '|ов|ев|ей|ам|ям|ами|ями|ах|ях|а|я|о|е|ы|и|у|ю|й|ь')
# «ей» — родительный множественного («сигилов» есть, а «печатей» не было) и
# творительный женского («стражей»). Без него правила глоссария молча пропускали
# целый падеж: замер по корпусу дал 19 находок и ни одного ложного срабатывания.
STRIP = re.compile(r'(?:ый|ий|ой|ая|яя|ое|ее|ые|ие|а|я|о|е|ы|и|й|ь)$')

def ban_pattern(ban):
    """Запрещённая форма во всех падежах: «Крита» -> Крит + окончание."""
    parts = []
    for word in ban.split():
        if re.fullmatch(r'[А-Яа-яЁё-]{5,}', word):
            stem = STRIP.sub('', word)
            if len(stem) >= 4:
                parts.append(re.escape(stem) + '(?:' + RU_END + ')?')
                continue
        parts.append(re.escape(word))
    return r'(?<![А-Яа-яЁё])' + r'\s+'.join(parts) + r'(?![А-Яа-яЁё])'

def load_glossary_bans(path=None):
    path = path or os.path.join(os.path.dirname(os.path.abspath(__file__)), 'GLOSSARY.md')
    rules = []
    try:
        lines = open(path, encoding='utf-8').read().splitlines()
    except OSError:
        return rules
    for line in lines:
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) < 3 or cells[0] in ('EN', '---'):
            continue
        ens = [re.sub(r'\(.*?\)', '', x).strip() for x in cells[0].split('/')]
        ens = [e for e in ens if re.fullmatch(r"[A-Za-z' ]{3,}", e)]
        bans = []
        for m in re.finditer(r'~~([^~]+)~~', cells[2]):
            bans += [x.strip() for x in m.group(1).split('/') if len(x.strip()) > 3]
        if ens and bans:
            # Апостроф в имени бывает и типографским: «Divinity's Reach» в одних
            # строках игры, «Divinity’s Reach» в других. Правило, собранное по
            # ASCII-апострофу, вторые молча пропускало.
            en_re = re.compile('|'.join(r'\b' + re.escape(e).replace("'", "['’ʼ]") + r'\w{0,3}\b'
                                        for e in ens), re.I)
            # Если «НЕ так» отличается от канона только регистром («Дозор Духов» /
            # «Дозор духов») — правило про регистр, ищем точно. Иначе регистр не важен.
            ban_re = [(b, re.compile(ban_pattern(b),
                                     0 if b.lower() == cells[1].lower() else re.I))
                      for b in bans]
            # Запрет бывает куском самого канона: «Огненное Сердце» лежит внутри
            # «Возвышенности Огненного Сердца», «Гендарран» — внутри «Гендарранских
            # полей». Без оговорки правило ругается на верный перевод.
            canon_re = re.compile(ban_pattern(cells[1].split(' / ')[0]), re.I)
            rules.append((en_re, cells[1], ban_re, canon_re))
    return rules

